    A(P("A middle path is to combine TF-IDF feature extraction with a linear "
        "classifier. This delivers strong accuracy on short, keyword-heavy texts such "
        "as complaints, trains in seconds on a laptop, needs no GPU, and is fully "
        "interpretable. CivicSense adopts this as the primary model and keeps a "
        "zero-shot DistilBERT path available behind a feature flag for demonstration "
        "purposes."))
    A(P("The interpretability argument deserves emphasis. A linear SVM\u2019s decision "
        "is a weighted sum of term features, so it is straightforward to inspect which "
        "words drive a particular classification. A transformer\u2019s decision is not "
        "directly inspectable. For a public-sector triage tool where an officer may "
        "have to defend an automated routing decision, the simpler model has a real "
        "advantage beyond its speed."))
    A(H2("2.3 Generative AI for Summarisation"))
    A(P("Generative models have been used in healthcare and legal services to produce "
        "patient summaries and case briefs. The base paper observes that this "
        "capability has not been widely applied to citizen-to-government complaint "
        "analysis. A city administrator does not want a list of one thousand "
        "complaints; they want a weekly digest of the form: \u201cWard 7 had 35 road "
        "complaints this week, the recurring concern being potholes - High Priority.\u201d "
        "Closing this gap is the central motivation of CivicSense."))
    A(P("Two implementation strategies exist for this kind of narrative output. The "
        "first is to call a large language model with the period\u2019s statistics and "
        "let it write the prose. The second is to compute the same statistics "
        "deterministically and generate the narrative from a template. The first "
        "produces more fluent language but depends on network access, cost and an API "
        "key. The second is reproducible, free and always available, at the cost of "
        "some fluency. CivicSense implements both and prefers the template engine by "
        "default, so the demonstration never depends on an external service."))
    A(H2("2.4 Smart-City Adjacent Work"))
    A(P("Predictive models forecast water-pipe bursts, machine learning optimises "
        "traffic flow, and IoT-connected garbage bins streamline collection routes. "
        "These systems optimise municipal assets from historical telemetry. Complaint "
        "analysis optimises a different signal - the citizen\u2019s voice - and feeds "
        "it into the same decisions. Sentiment analysis of social-media posts measures "
        "public mood but cannot pinpoint a specific service failure at ward level. "
        "CivicSense combines classification, prioritisation and summarisation to close "
        "that gap."))
    A(P("The distinction matters practically. An IoT bin sensor tells you a bin is "
        "full; it does not tell you that forty citizens have already complained about "
        "overflowing bins on the same street, which is a different and stronger signal "
        "about service failure. Combining citizen text with asset telemetry is a "
        "natural future step, and is listed in Section 9."))
    A(H2("2.5 Abuse and Fraud in Public Reporting Systems"))
    A(P("Open reporting channels are inherently vulnerable to abuse. A body of work on "
        "spam and Sybil attacks in public platforms has established three recurring "
        "patterns relevant to civic complaint intake: bursts of activity concentrated "
        "in a narrow time window, near-identical content submitted repeatedly, and "
        "content that is too short or generic to be verified. These are the same "
        "signals that fraud engines use in review and social platforms, and they "
        "transfer naturally to the complaint domain."))
    A(P("The design consequence is that fraud detection should be kept separate from "
        "deduplication. A genuine citizen re-filing a legitimate complaint and a bot "
        "flooding a channel can produce the same text and, superficially, the same "
        "similarity score. Duplicate detection asks \u201cis this the same issue?\u201d "
        "whereas fraud detection asks \u201cwas this filed in bad faith?\u201d Merging "
        "them would punish legitimate duplicates. CivicSense therefore implements them "
        "as two independent modules with distinct outputs."))
    A(H2("2.6 Duplicate Detection and Incident Clustering"))
    A(P("Classical deduplication compares normalised text with a similarity measure "
        "such as Jaccard overlap, cosine similarity over TF-IDF vectors, or "
        "edit-distance ratios. These approaches are cheap and deterministic but brittle "
        "to paraphrase: \u201ca tree fell on the road\u201d and \u201ca fallen branch "
        "blocked traffic\u201d share almost no surface tokens while describing the same "
        "incident."))
    A(P("Embedding-based approaches solve this by comparing meaning rather than wording. "
        "Sentence-BERT and similar encoders map paraphrases to nearby vectors, so a "
        "single similarity threshold can group them. Incident clustering is the natural "
        "extension of this idea: rather than merely flagging one record as a duplicate "
        "of another, reports are grouped into clusters that represent distinct open "
        "incidents. This shift from pairwise deduplication to clustering is what allows "
        "a system to answer \u201chow many distinct incidents are open?\u201d instead of "
        "\u201chow many records exist?\u201d."))
    A(P("A practical difficulty is that embedding libraries add heavy dependencies. "
        "CivicSense addresses this by making embeddings the preferred path and providing "
        "a deterministic difflib-based fallback on normalised text, so the clustering "
        "feature degrades gracefully instead of disappearing when the embedding stack "
        "is unavailable."))
    A(H2("2.7 Explainable AI in Public-Sector Decisions"))
    A(P("Automated decisions in public administration carry a legitimacy requirement "
        "that decisions in many other domains do not. A citizen whose complaint is "
        "deprioritised is entitled to know why, and an officer who overrides a machine "
        "ranking needs to understand what the machine thought it saw. Explainable AI "
        "research distinguishes between intrinsic explainability (the model is simple "
        "enough to inspect) and post-hoc explainability (a separate method explains the "
        "model)."))
    A(P("CivicSense uses both. The classifier is intrinsically explainable because it "
        "is a linear model over term features. The priority and fraud engines, which "
        "combine several weighted signals, are explained post-hoc by converting their "
        "numeric breakdowns into natural-language sentences. This is a lighter-weight "
        "and more auditable approach than attributing a deep model\u2019s output, and "
        "it is well matched to the domain, where the contributing factors are already "
        "defined and bounded."))
